"""Opt-in numerical comparisons between pyBrainAnalyzIR and MATLAB nirs-toolbox."""
from __future__ import annotations

from contextlib import ExitStack
from dataclasses import dataclass
import json
from math import gamma
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
from typing import Any, Literal

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import xarray as xr
from scipy.stats import t as student_t


_MATLAB_DRIVER = Path(__file__).parent / "matlab" / "run_reference_comparison.m"
_SIMULATIONS = ("simData", "simMotionArtifact")
_SIGNAL_TYPES = ("hbo", "hbr")
_PYTHON_SIGNAL_TYPES = ("HbO", "HbR")
_STATISTIC_KEYS = (
    "iteration",
    "source",
    "detector",
    "signal_type",
    "condition",
)


@dataclass(frozen=True)
class ROCCurve:
    """ROC points returned by one toolbox for one hemoglobin type."""

    true_positive_rate: np.ndarray
    false_positive_rate: np.ndarray
    thresholds: np.ndarray


@dataclass
class MatlabPythonComparison:
    """Numerical outputs and ROC curves from a shared set of simulated inputs."""

    estimates: pd.DataFrame
    curves: dict[str, dict[str, ROCCurve]]
    summary: dict[str, Any]
    figure: Any
    output_dir: Path | None


def find_matlab_executable(matlab_executable: str | Path | None = None) -> str:
    """Find MATLAB from an explicit path, environment variable, PATH, or macOS app."""
    requested = matlab_executable or os.environ.get("PYBRAIN_MATLAB_EXECUTABLE")
    if requested:
        path = Path(requested).expanduser()
        if not path.is_file():
            raise FileNotFoundError(f"MATLAB executable does not exist: {path}")
        return str(path.resolve())

    on_path = shutil.which("matlab")
    if on_path:
        return on_path

    if sys.platform == "darwin":
        app_executables = sorted(Path("/Applications").glob("MATLAB_R*.app/bin/matlab"))
        if app_executables:
            return str(app_executables[-1])

    raise FileNotFoundError(
        "MATLAB was not found. Set PYBRAIN_MATLAB_EXECUTABLE or pass "
        "matlab_executable to run_matlab_python_roc_comparison()."
    )


def run_matlab_python_roc_comparison(
    num_iterations: int = 50,
    *,
    seed: int = 13,
    simulation: Literal["simData", "simMotionArtifact"] = "simData",
    output_dir: str | Path | None = None,
    matlab_executable: str | Path | None = None,
    timeout: float = 7200,
) -> MatlabPythonComparison:
    """Compare matched MATLAB and Python preprocessing/GLM results.

    Each iteration is generated by the selected MATLAB simulation function and
    saved as SNIRF. The same raw file and ground truth are then used by both
    toolboxes. ``simMotionArtifact`` uses its default rate of 2 spikes/minute
    and 0.5 shifts/minute.
    MATLAB Beer-Lambert PPF and Python MBLL DPF are both set to 6, with no
    partial-volume correction. Both pipelines resample to 4 Hz and use
    AR-IRLS with order 16 and MATLAB's Canonical double-gamma HRF basis.

    If ``output_dir`` is given, a unique run folder is created beneath it with
    the generated inputs, per-estimate CSV, summary JSON, ROC CSV, and plot.
    MATLAB must be installed locally with nirs-toolbox on its startup path.
    """
    if isinstance(num_iterations, bool) or not isinstance(num_iterations, int) or num_iterations < 1:
        raise ValueError("num_iterations must be a positive integer")
    if isinstance(seed, bool) or not isinstance(seed, int):
        raise ValueError("seed must be an integer")
    if simulation not in _SIMULATIONS:
        raise ValueError(
            f"simulation must be one of {_SIMULATIONS}, got {simulation!r}"
        )
    if timeout <= 0:
        raise ValueError("timeout must be greater than zero")
    if not _MATLAB_DRIVER.is_file():
        raise FileNotFoundError(f"MATLAB comparison driver is missing: {_MATLAB_DRIVER}")

    executable = find_matlab_executable(matlab_executable)
    with ExitStack() as stack:
        if output_dir is not None:
            output_root = Path(output_dir).expanduser()
            output_root.mkdir(parents=True, exist_ok=True)
            work_dir = Path(tempfile.mkdtemp(prefix="matlab-comparison-", dir=output_root))
            keep_work_dir = True
        else:
            temporary_directory = stack.enter_context(
                tempfile.TemporaryDirectory(prefix="matlab-comparison-")
            )
            work_dir = Path(temporary_directory)
            keep_work_dir = False
        _run_matlab_driver(
            executable, work_dir, num_iterations, seed, simulation, timeout
        )
        result = _compare_python_results(work_dir, num_iterations, seed, simulation)
        if keep_work_dir:
            result.output_dir = work_dir
            _save_results(result, work_dir)
        return result


def _run_matlab_driver(
    executable: str,
    output_dir: Path,
    num_iterations: int,
    seed: int,
    simulation: str,
    timeout: float,
) -> None:
    matlab_directory = str(_MATLAB_DRIVER.parent.resolve()).replace("'", "''")
    command = [
        executable,
        "-batch",
        f"addpath('{matlab_directory}'); run_reference_comparison()",
    ]
    environment = os.environ.copy()
    environment.update({
        "PYBRAIN_MATLAB_COMPARISON_OUTPUT": str(output_dir.resolve()),
        "PYBRAIN_MATLAB_COMPARISON_ITERATIONS": str(num_iterations),
        "PYBRAIN_MATLAB_COMPARISON_SEED": str(seed),
        "PYBRAIN_MATLAB_COMPARISON_SIMULATION": simulation,
    })
    completed = subprocess.run(
        command,
        check=False,
        capture_output=True,
        text=True,
        timeout=timeout,
        env=environment,
    )
    (output_dir / "matlab_stdout.log").write_text(completed.stdout)
    (output_dir / "matlab_stderr.log").write_text(completed.stderr)
    if completed.returncode != 0:
        details = completed.stderr.strip() or completed.stdout.strip() or "No MATLAB output"
        raise RuntimeError(
            f"MATLAB comparison failed with exit status {completed.returncode}:\n{details}"
        )


def _compare_python_results(
    work_dir: Path,
    num_iterations: int,
    seed: int,
    simulation: str,
) -> MatlabPythonComparison:
    from cedalion.io.snirf import read_snirf

    import pyBrainAnalyzIR.pipelines.modules.glm as glm
    import pyBrainAnalyzIR.pipelines.modules.preproccessing as prep
    import pyBrainAnalyzIR.testing.channelROC as channel_roc

    reference = pd.read_csv(work_dir / "matlab_statistics.csv")
    required_columns = {
        *_STATISTIC_KEYS,
        "beta",
        "t_value",
        "p_value",
        "dof",
        "truth",
    }
    missing_columns = required_columns - set(reference.columns)
    if missing_columns:
        raise ValueError(f"MATLAB statistics are missing columns: {sorted(missing_columns)}")
    reference["signal_type"] = reference["signal_type"].astype(str).str.lower()
    reference["condition"] = reference["condition"].astype(str)
    reference = reference[reference["condition"] == "A"].copy()

    matlab_roc_frame = pd.read_csv(work_dir / "matlab_roc.csv")
    pipeline = prep.intensity_opticaldensity()
    pipeline = prep.mbll(pipeline)
    pipeline = prep.resample(pipeline)
    pipeline = glm.GLM(pipeline)
    pipeline.set_all_options({
        "basis_function": _matlab_canonical_basis(),
        "dpf": [6, 6],
        "Fs": 4,
        "noise_model": "ar_irls",
        "ar_order": 16,
        "verbose": False,
    })
    model = channel_roc.ChannelROC()
    model.pipeline = pipeline
    model.condition = "A"

    np.random.seed(seed)
    python_estimates = []
    for iteration in range(1, num_iterations + 1):
        input_file = work_dir / "inputs" / f"iteration_{iteration:03d}.snirf"
        recordings = read_snirf(input_file)
        if len(recordings) != 1:
            raise ValueError(
                f"Expected one recording in {input_file}, found {len(recordings)}"
            )
        recording = recordings[0]
        _prepare_recording_for_python_mbll(recording)
        truth = _truth_for_recording(
            recording,
            reference[reference["iteration"] == iteration],
        )

        processed = model.pipeline.run(recording)
        statistics = processed[model._stats_name()]
        python_pvalues = model._condition_pvalues(statistics, truth)
        model._pvals.append(python_pvalues)
        model._truth.append(np.asarray(truth.data))
        model.iterations += 1
        python_estimates.append(_condition_estimates(statistics, model, iteration))

    python_frame = pd.concat(python_estimates, ignore_index=True)
    estimates = _merge_estimates(reference, python_frame)
    matlab_curves = _matlab_curves(matlab_roc_frame)
    python_tpr, python_fpr, python_thresholds = model.results()
    python_curves = {
        signal_type: ROCCurve(
            true_positive_rate=np.asarray(python_tpr[index]),
            false_positive_rate=np.asarray(python_fpr[index]),
            thresholds=np.asarray(python_thresholds[index]),
        )
        for index, signal_type in enumerate(_SIGNAL_TYPES)
    }
    curves = {"matlab": matlab_curves, "python": python_curves}
    summary = _comparison_summary(
        estimates, curves, seed, num_iterations, simulation
    )
    figure = _plot_roc_comparison(
        curves,
        _satterthwaite_type_one_curves(estimates),
    )
    metadata_path = work_dir / "matlab_metadata.json"
    if metadata_path.exists():
        summary["matlab"] = json.loads(metadata_path.read_text())
    return MatlabPythonComparison(
        estimates=estimates,
        curves=curves,
        summary=summary,
        figure=figure,
        output_dir=None,
    )


def _matlab_canonical_basis() -> Any:
    """Build the MATLAB nirs-toolbox Canonical double-gamma HRF in Cedalion form."""
    from cedalion import units
    from cedalion.models.glm.basis_functions import TemporalBasisFunction
    from cedalion.sigproc.frequency import sampling_rate

    class MatlabCanonicalBasis(TemporalBasisFunction):
        def __init__(self) -> None:
            super().__init__(convolve_over_duration=True)

        def __call__(self, ts: Any) -> xr.DataArray:
            sampling_frequency = float(sampling_rate(ts).to(units.Hz).magnitude)
            time = np.arange(0, 32 * sampling_frequency + 1) / sampling_frequency
            response = (
                time**3 * np.exp(-time) / gamma(4)
                - (1 / 6) * time**15 * np.exp(-time) / gamma(16)
            )
            response /= response.sum()
            time_coordinate = (
                xr.DataArray(time, dims=["time"], attrs={"units": "s"})
                .pint.quantify()
                .pint.dequantify()
            )
            return xr.DataArray(
                response[:, None],
                dims=("time", "component"),
                coords={"time": time_coordinate, "component": ["canonical"]},
            )

    return MatlabCanonicalBasis()


def _prepare_recording_for_python_mbll(recording: Any) -> None:
    """Adapt MATLAB's planar SNIRF geometry/time metadata to Cedalion's MBLL input."""
    from cedalion import units

    if recording.geo3d.sizes.get("label", 0) == 0:
        planar = recording.geo2d.pint.dequantify()
        positions = np.asarray(planar.data, dtype=float)
        if positions.ndim != 2 or positions.shape[1] != 2:
            raise ValueError("MATLAB simulation SNIRF must contain a 2D probe layout")
        coordinates = {
            name: coordinate
            for name, coordinate in planar.coords.items()
            if "pos" not in coordinate.dims
        }
        attrs = dict(planar.attrs)
        attrs["units"] = "mm"
        recording.geo3d = xr.DataArray(
            np.column_stack((positions, np.zeros(positions.shape[0]))),
            dims=("label", "pos"),
            coords=coordinates,
            attrs=attrs,
        ).pint.quantify()

    recording["amp"].time.attrs.setdefault("units", units.s)


def _source_detector_pair(channel: Any) -> tuple[int, int]:
    match = re.search(
        r"source-(\d+)detector-(\d+)",
        str(channel),
        flags=re.IGNORECASE,
    )
    if match is None:
        raise ValueError(f"Cannot parse MATLAB SNIRF channel label: {channel!r}")
    return int(match.group(1)), int(match.group(2))


def _truth_for_recording(recording: Any, reference: pd.DataFrame) -> xr.DataArray:
    lookup = {
        (int(row.source), int(row.detector), str(row.signal_type).lower()): float(row.truth)
        for row in reference.itertuples(index=False)
    }
    channels = np.asarray(recording["amp"].channel.values).astype(str)
    truth_values = np.full((len(channels), len(_SIGNAL_TYPES)), np.nan)
    for channel_index, channel in enumerate(channels):
        source, detector = _source_detector_pair(channel)
        for type_index, signal_type in enumerate(_SIGNAL_TYPES):
            key = (source, detector, signal_type)
            if key not in lookup:
                raise ValueError(f"MATLAB simulation truth is missing {key}")
            truth_values[channel_index, type_index] = lookup[key]
    return xr.DataArray(
        truth_values,
        dims=("channel", "type"),
        coords={"channel": channels, "type": list(_PYTHON_SIGNAL_TYPES)},
    )


def _condition_estimates(statistics: Any, model: Any, iteration: int) -> pd.DataFrame:
    frame = statistics.table()
    frame = frame[frame["Condition"].map(model._matches_condition)].copy()
    if frame.empty:
        raise ValueError(
            "Python GLM produced no estimates for the simulated condition 'A'"
        )
    source_detector = frame["Channel"].map(_source_detector_pair)
    frame["source"] = source_detector.map(lambda pair: pair[0])
    frame["detector"] = source_detector.map(lambda pair: pair[1])
    frame["signal_type"] = frame["Type"].astype(str).str.lower()
    frame["iteration"] = iteration
    frame["condition"] = "A"
    dof_lookup = {
        (str(channel), str(chromo)): float(value)
        for channel in statistics.satterthwaite_dof.channel.values
        for chromo in statistics.satterthwaite_dof.chromo.values
        for value in [
            statistics.satterthwaite_dof.sel(channel=channel, chromo=chromo).item()
        ]
    }
    frame["dof_satterthwaite_python"] = [
        dof_lookup[(str(channel), str(signal_type))]
        for channel, signal_type in zip(frame["Channel"], frame["Type"])
    ]
    frame["dof_python"] = statistics.dof
    frame["p_value_python_satterthwaite"] = 2 * student_t.sf(
        np.abs(frame["T-value"].to_numpy(dtype=float)),
        frame["dof_satterthwaite_python"].to_numpy(dtype=float),
    )
    return frame.rename(columns={
        "Beta": "beta_python",
        "T-value": "t_value_python",
        "P-values": "p_value_python",
        "dof": "dof_python",
    })[[
        "iteration",
        "source",
        "detector",
        "signal_type",
        "condition",
        "beta_python",
        "t_value_python",
        "p_value_python",
        "dof_python",
        "dof_satterthwaite_python",
        "p_value_python_satterthwaite",
    ]]


def _merge_estimates(reference: pd.DataFrame, python: pd.DataFrame) -> pd.DataFrame:
    reference = reference.rename(columns={
        "beta": "beta_matlab",
        "t_value": "t_value_matlab",
        "p_value": "p_value_matlab",
        "dof": "dof_matlab",
        "truth": "truth_matlab",
    })
    python = python.copy()
    truth_keys = reference[
        [*_STATISTIC_KEYS, "truth_matlab"]
    ].rename(columns={"truth_matlab": "truth_python"})
    python = python.merge(
        truth_keys,
        on=list(_STATISTIC_KEYS),
        how="left",
        validate="one_to_one",
    )
    merged = reference.merge(
        python,
        on=list(_STATISTIC_KEYS),
        how="outer",
        validate="one_to_one",
        indicator=True,
    )
    unmatched = merged["_merge"] != "both"
    if unmatched.any():
        keys = merged.loc[unmatched, list(_STATISTIC_KEYS)].head(5).to_dict("records")
        raise ValueError(f"MATLAB and Python GLM estimates did not align: {keys}")
    truth_matches = (
        merged["truth_matlab"].eq(merged["truth_python"])
        | (merged["truth_matlab"].isna() & merged["truth_python"].isna())
    )
    if not truth_matches.all():
        raise ValueError("The MATLAB and Python ground-truth channel labels differ")
    return merged.drop(columns=["_merge", "truth_python"])


def _matlab_curves(frame: pd.DataFrame) -> dict[str, ROCCurve]:
    curves = {}
    for signal_type in _SIGNAL_TYPES:
        selected = frame[frame["signal_type"].astype(str).str.lower() == signal_type]
        if selected.empty:
            raise ValueError(f"MATLAB ROC output is missing signal type {signal_type}")
        selected = selected.sort_values("point")
        curves[signal_type] = ROCCurve(
            true_positive_rate=selected["true_positive_rate"].to_numpy(dtype=float),
            false_positive_rate=selected["false_positive_rate"].to_numpy(dtype=float),
            thresholds=selected["threshold"].to_numpy(dtype=float),
        )
    return curves


def _metric_pair(matlab: np.ndarray, python: np.ndarray) -> dict[str, float | int | None]:
    valid = np.isfinite(matlab) & np.isfinite(python)
    left = matlab[valid]
    right = python[valid]
    if not left.size:
        return {
            "count": 0,
            "mean_absolute_error": None,
            "max_absolute_error": None,
            "root_mean_square_error": None,
            "pearson_correlation": None,
        }
    difference = left - right
    correlation = (
        float(np.corrcoef(left, right)[0, 1])
        if left.size > 1 and np.std(left) > 0 and np.std(right) > 0
        else None
    )
    return {
        "count": int(left.size),
        "mean_absolute_error": float(np.mean(np.abs(difference))),
        "max_absolute_error": float(np.max(np.abs(difference))),
        "root_mean_square_error": float(np.sqrt(np.mean(difference**2))),
        "pearson_correlation": correlation,
    }


def _comparison_summary(
    estimates: pd.DataFrame,
    curves: dict[str, dict[str, ROCCurve]],
    seed: int,
    num_iterations: int,
    simulation: str,
) -> dict[str, Any]:
    metrics = {
        name: _metric_pair(
            estimates[f"{name}_matlab"].to_numpy(dtype=float),
            estimates[f"{name}_python"].to_numpy(dtype=float),
        )
        for name in ("beta", "t_value", "p_value")
    }
    type_one_error = {}
    null_estimates = estimates[estimates["truth_matlab"] == 0]
    for signal_type in _SIGNAL_TYPES:
        selected = null_estimates[
            null_estimates["signal_type"].astype(str).str.lower() == signal_type
        ]
        type_one_error[signal_type] = {}
        for label, column in (
            ("matlab", "p_value_matlab"),
            ("python", "p_value_python"),
            ("python_satterthwaite", "p_value_python_satterthwaite"),
        ):
            values = selected[column].to_numpy(dtype=float)
            type_one_error[signal_type][label] = {
                "n_null": int(np.isfinite(values).sum()),
                "rates": {
                    str(alpha): float(np.mean(values <= alpha))
                    for alpha in (0.01, 0.05, 0.1)
                },
                "mean_absolute_error_from_nominal": float(
                    np.mean([
                        abs(np.mean(values <= alpha) - alpha)
                        for alpha in (0.01, 0.05, 0.1)
                    ])
                ),
            }
    roc_metrics = {}
    fpr_grid = np.linspace(0, 1, 1001)
    for signal_type in _SIGNAL_TYPES:
        matlab = curves["matlab"][signal_type]
        python = curves["python"][signal_type]
        matlab_tpr = np.interp(
            fpr_grid, matlab.false_positive_rate, matlab.true_positive_rate
        )
        python_tpr = np.interp(
            fpr_grid, python.false_positive_rate, python.true_positive_rate
        )
        difference = np.abs(matlab_tpr - python_tpr)
        roc_metrics[signal_type] = {
            "mean_absolute_tpr_difference": float(difference.mean()),
            "max_absolute_tpr_difference": float(difference.max()),
        }
    return {
        "iterations": num_iterations,
        "seed": seed,
        "configuration": {
            "simulation": simulation,
            "motion_spikes_per_minute": 2 if simulation == "simMotionArtifact" else None,
            "motion_shifts_per_minute": 0.5 if simulation == "simMotionArtifact" else None,
            "matlab_ppf": 6,
            "python_dpf": [6, 6],
            "partial_volume_correction": False,
            "sampling_frequency_hz": 4,
            "glm_noise_model": "AR-IRLS",
            "ar_order": 16,
            "hrf_basis": "nirs.design.basis.Canonical in both toolboxes",
        },
        "estimate_comparison": metrics,
        "degrees_of_freedom": {
            "matlab": _finite_summary(estimates["dof_matlab"]),
            "python_current": _finite_summary(estimates["dof_python"]),
            "python_satterthwaite_candidate": _finite_summary(
                estimates["dof_satterthwaite_python"]
            ),
        },
        "type_one_error": type_one_error,
        "roc_comparison": roc_metrics,
    }


def _finite_summary(values: pd.Series) -> dict[str, float | None]:
    finite = values.to_numpy(dtype=float)
    finite = finite[np.isfinite(finite)]
    if not finite.size:
        return {"median": None, "minimum": None, "maximum": None}
    return {
        "median": float(np.median(finite)),
        "minimum": float(np.min(finite)),
        "maximum": float(np.max(finite)),
    }


def _satterthwaite_type_one_curves(
    estimates: pd.DataFrame,
) -> dict[str, ROCCurve]:
    curves = {}
    null_estimates = estimates[estimates["truth_matlab"] == 0]
    for signal_type in _SIGNAL_TYPES:
        selected = null_estimates[
            null_estimates["signal_type"].astype(str).str.lower() == signal_type
        ]
        thresholds = np.sort(
            selected["p_value_python_satterthwaite"].to_numpy(dtype=float)
        )
        thresholds = thresholds[np.isfinite(thresholds)]
        false_positive_rate = (
            np.arange(1, len(thresholds) + 1) / len(thresholds)
            if len(thresholds)
            else np.array([], dtype=float)
        )
        curves[signal_type] = ROCCurve(
            true_positive_rate=np.array([], dtype=float),
            false_positive_rate=false_positive_rate,
            thresholds=thresholds,
        )
    return curves


def _plot_roc_comparison(
    curves: dict[str, dict[str, ROCCurve]],
    satterthwaite_type_one_curves: dict[str, ROCCurve] | None = None,
) -> Any:
    figure, (roc_axis, type_one_axis) = plt.subplots(1, 2, figsize=(13, 5))
    colors = {"hbo": "tab:red", "hbr": "tab:blue"}
    for signal_type in _SIGNAL_TYPES:
        color = colors[signal_type]
        for toolbox, linestyle in (("matlab", "-"), ("python", "--")):
            curve = curves[toolbox][signal_type]
            label = f"{toolbox.title()} {signal_type.upper()}"
            roc_axis.plot(
                curve.false_positive_rate,
                curve.true_positive_rate,
                color=color,
                linestyle=linestyle,
                label=label,
            )
            type_one_axis.plot(
                curve.thresholds,
                curve.false_positive_rate,
                color=color,
                linestyle=linestyle,
                label=label,
            )
        if satterthwaite_type_one_curves is not None:
            curve = satterthwaite_type_one_curves[signal_type]
            type_one_axis.plot(
                curve.thresholds,
                curve.false_positive_rate,
                color=color,
                linestyle=":",
                label=f"Python Satterthwaite {signal_type.upper()}",
            )

    roc_axis.plot([0, 1], [0, 1], color="0.6", linestyle=":")
    roc_axis.set(
        title="ROC curves",
        xlabel="False positive rate",
        ylabel="True positive rate",
        xlim=(0, 1),
        ylim=(0, 1),
    )
    type_one_axis.set(
        title="Type-I error",
        xlabel="P-value threshold",
        ylabel="False positive rate",
        xlim=(0, 1),
        ylim=(0, 1),
    )
    type_one_axis.plot(
        [0, 1],
        [0, 1],
        color="black",
        linestyle=":",
        label="Nominal FPR = threshold",
    )
    for axis in (roc_axis, type_one_axis):
        axis.grid(True, alpha=0.25)
        axis.legend()
    figure.tight_layout()
    return figure


def _save_results(result: MatlabPythonComparison, output_dir: Path) -> None:
    result.estimates.to_csv(output_dir / "estimate_comparison.csv", index=False)
    with (output_dir / "comparison_summary.json").open("w") as stream:
        json.dump(result.summary, stream, indent=2, allow_nan=False)

    roc_rows = []
    for toolbox, signal_curves in result.curves.items():
        for signal_type, curve in signal_curves.items():
            roc_rows.extend({
                "toolbox": toolbox,
                "signal_type": signal_type,
                "point": point,
                "true_positive_rate": true_positive_rate,
                "false_positive_rate": false_positive_rate,
                "threshold": threshold,
            } for point, (true_positive_rate, false_positive_rate, threshold) in enumerate(
                zip(
                    curve.true_positive_rate,
                    curve.false_positive_rate,
                    curve.thresholds,
                ),
                start=1,
            ))
    pd.DataFrame(roc_rows).to_csv(output_dir / "roc_comparison.csv", index=False)
    result.figure.savefig(output_dir / "roc_comparison.png", dpi=160)
